import numpy as np
from langchain_ollama import OllamaEmbeddings

router_embeddings = OllamaEmbeddings(
    model="qwen3-embedding:0.6b",
    num_gpu=1
)

ROUTER_EXAMPLE_EMBEDDINGS = {}

for intent, examples in ROUTER_EXAMPLES.items():

    ROUTER_EXAMPLE_EMBEDDINGS[intent] = (
        router_embeddings.embed_documents(examples)
    )

def cosine_similarity(a, b):

    a = np.asarray(a)
    b = np.asarray(b)

    denominator = (
        np.linalg.norm(a) *
        np.linalg.norm(b)
    )

    if denominator == 0:
        return 0.0

    return float(np.dot(a, b) / denominator)

def classify_query_intent(query):
    query_embedding = router_embeddings.embed_query(query)

    intent_scores = {}

    for intent, example_embeddings in ROUTER_EXAMPLE_EMBEDDINGS.items():
        similarities = [
            cosine_similarity(query_embedding, example_embedding)
            for example_embedding in example_embeddings
        ]
        intent_scores[intent] = max(similarities)

    best_intent = max(
        intent_scores,
        key=intent_scores.get
    )

    best_similarity = intent_scores[best_intent]

    print("\n[INTENT ROUTER]")
    print(f"HYBRID : {intent_scores['HYBRID']:.4f}")
    print(f"GRAPH  : {intent_scores['GRAPH']:.4f}")
    print(f"GIT    : {intent_scores['GIT']:.4f}")
    print(f"Best   : {best_intent}")

    return {
        "route": best_intent,
        "similarity": best_similarity,
        "scores": intent_scores
    }

def stage0_process_query(query, repository_name, ollama_client):

    guardrail_result = repository_domain_guardrail(
        query=query,
        repository_name=repository_name,
        ollama_client=ollama_client
    )

    if guardrail_result["decision"] == "REJECT":
        return {
            "status": "REJECTED",
            "domain": "GENERAL",
            "route": None,
            "confidence": 0.0,
            "routing_mode": None
        }

    routing_result = classify_query_intent(query)

    route = routing_result["route"]
    similarity = routing_result["similarity"]

    return {
    "status": "ALLOWED",
    "domain": "REPOSITORY",
    "route": route,
    "similarity": similarity,
    "intent_scores": routing_result.get("scores", {})
}


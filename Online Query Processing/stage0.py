import ollama

ollama_client = ollama.Client(
    host="http://localhost:11434"
)

DOMAIN_GUARDRAIL_PROMPT = """
You are a repository-domain filter.

Repository:
{repository_name}

User query:
{query}

Your task is to determine whether the query could reasonably be answered
using information from the specified software repository.

Classify as:

REPOSITORY
- The query directly asks about the repository's source code, files,
  classes, methods, functions, modules, implementation, behavior,
  structure, dependencies, or architecture.
- The query asks about commits, changes, history, blame, authorship,
  revisions, or diffs.
- The query asks "why", "how", "what", "where", or "who" about something
  that may refer to the repository.
- The query is about modifying, debugging, understanding, or analyzing
  code and repository context could be relevant.
- The query does not explicitly mention the repository but could still
  reasonably refer to it.
- If the query is ambiguous but could reasonably refer to the repository,
  classify it as REPOSITORY.

GENERAL
- The query is clearly unrelated to the repository and clearly asks for
  general-world information such as weather, geography, entertainment,
  sports, general trivia, or casual conversation.
- The query clearly does not require or benefit from repository information.

Important:
When uncertain, choose REPOSITORY.

Do NOT try to determine which repository route should handle the query.
Only determine whether the repository could be relevant.

Return ONLY one of:

DOMAIN: REPOSITORY

or

DOMAIN: GENERAL
"""
def repository_domain_guardrail(
    query: str,
    repository_name: str,
    ollama_client
):
    prompt = DOMAIN_GUARDRAIL_PROMPT.format(
        repository_name=repository_name,
        query=query
    )

    response = ollama_client.generate(
        model="qwen2.5-coder:7b-instruct-q4_K_M",
        prompt=prompt,
        options={
            "temperature": 0.0,
            "num_predict": 8,
        }
    )

    result = response.get("response", "").strip().upper()

    if "DOMAIN: GENERAL" in result:
        return {
            "decision": "REJECT",
            "domain": "GENERAL"
        }

    if "DOMAIN: REPOSITORY" in result:
        return {
            "decision": "ALLOW",
            "domain": "REPOSITORY"
        }

    # Ambiguous/unexpected output:
    # allow it to proceed to the actual intent router.
    return {
        "decision": "ALLOW",
        "domain": "REPOSITORY"
    }
    

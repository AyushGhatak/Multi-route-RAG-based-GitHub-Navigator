    children = cand.get("children") or []

    if children:

        lines.append(
            "Children:"
        )

        for child in children:

            child_line = (
                f'- {child.get("name", "Unknown")} '
                f'({child.get("type", "UNKNOWN")}) '
                f'[{child.get("file_path", "")}]'
            )

            if child.get("signature"):

                child_line += (
                    f'\n  Signature: '
                    f'{child["signature"]}'
                )

            if child.get("docstring"):

                child_line += (
                    f'\n  Docstring: '
                    f'{child["docstring"]}'
                )

            if child.get("body"):

                child_line += (
                    f'\n  Body:\n'
                    f'  {child["body"]}'
                )

            lines.append(
                child_line
            )


    # Continuation chunks
    next_chunks = (
        cand.get("next_chunks") or []
    )

    if next_chunks:

        lines.append("Code continuation chunks:")

        for chunk in next_chunks:
          lines.append(
              f'- Chunk ID: {chunk.get("id", "unknown")}'
          )

          if chunk.get("file_path"):
              lines.append(
                  f'  File: {chunk["file_path"]}'
              )

          if chunk.get("name"):
              lines.append(
                  f'  Name: {chunk["name"]}'
              )

          if chunk.get("type"):
              lines.append(
                  f'  Type: {chunk["type"]}'
              )

          if chunk.get("body"):
              lines.append(
                  f'  Body:\n'
                  f'  {chunk["body"]}'
              )
              
    # Reranking metadata
    lines.append(
        f'Graph rerank score: '
        f'{cand.get("rerank_score", 0.0):.4f}'
    )

    lines.append(
        f'Graph semantic score: '
        f'{cand.get("graph_semantic_score", 0.0):.4f}'
    )

    return "\n".join(lines) + "\n\n"



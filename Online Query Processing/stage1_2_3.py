def compress_graph_context_to_budget(
    reranked_candidates: List[Dict[str, Any]],
    max_token_budget: int = 2800,
    is_membership_query: bool = False
) -> List[Dict[str, Any]]:

    compressed_results = []
    accumulated_tokens = 0

    for original_cand in reranked_candidates:

        # 1. GRAPH-SPECIFIC NORMALIZATION
        cand = normalize_graph_candidate(
            original_cand
        )

        # 2. PRIMARY IMPLEMENTATION BODY
        entity = cand.get(
            "entity_type",
            "UNKNOWN"
        ).upper()

        original_body = (
            cand.get(
                "implementation_body",
                ""
            )
            or ""
        )

        entity_limit = ENTITY_TOKEN_LIMITS.get(
            entity,
            ENTITY_TOKEN_LIMITS["UNKNOWN"]
        )

        truncated_body = truncate_text(
            original_body,
            entity_limit
        )

        cand["implementation_body"] = (
            truncated_body
        )

        cand["is_truncated"] = (
            truncated_body != original_body
        )

        # 3. PARENT CONTEXT
        cand["parent_body"] = truncate_text(
            cand.get("parent_body", ""),
            300
        )

        cand["parent_docstring"] = truncate_text(
            cand.get("parent_docstring", ""),
            150
        )

        # 4. CHILDREN
        normalized_children = []

        for child in (
            cand.get("children") or []
        ):

            normalized_children.append({

                "id": child.get("id"),

                "name": child.get(
                    "name",
                    ""
                ),

                "type": child.get(
                    "type",
                    ""
                ),

                "file_path": child.get(
                    "file_path",
                    ""
                ),

                "signature": child.get(
                    "signature",
                    ""
                ),

                "docstring": truncate_text(
                    child.get(
                        "docstring",
                        ""
                    ),
                    100
                ),

                "body": truncate_text(
                    child.get(
                        "body",
                        ""
                    ),
                    150
                )
            })

        cand["children"] = (
            normalized_children
        )

        # 5. NEXT CHUNKS
        normalized_next_chunks = []

        for chunk in (
            cand.get("next_chunks") or []
        ):

            normalized_next_chunks.append({

                "id": chunk.get(
                    "id"
                ),

                "file_path": chunk.get(
                    "file_path",
                    ""
                ),

                "name": chunk.get(
                    "name",
                    ""
                ),

                "type": chunk.get(
                    "type",
                    ""
                ),

                "body": truncate_text(
                    chunk.get(
                        "body",
                        ""
                    ),
                    200
                )
            })

        cand["next_chunks"] = (
            normalized_next_chunks
        )

        # 6. GRAPH-AWARE FORMATTING
        if is_membership_query:
            candidate_str = format_membership_candidate(cand)
        else:
            candidate_str = (
                format_graph_candidate_for_stage3(
                    cand
                )
            )

        # 7. TOKEN COUNT
        cand_tokens = count_tokens(
            candidate_str
        )

        # 8. GLOBAL TOKEN BUDGET
        if (
            accumulated_tokens
            + cand_tokens
            > max_token_budget
        ):
            break

        accumulated_tokens += cand_tokens

        cand["token_count"] = (
            cand_tokens
        )

        cand["formatted_context"] = (
            candidate_str
        )

        compressed_results.append(
            cand
        )

    return compressed_results



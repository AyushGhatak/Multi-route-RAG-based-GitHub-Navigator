@tool
def hybrid_search_route(query_text: str) -> List[dict]:
    """Performs a hybrid semantic and keyword search across the codebase AST/knowledge graph.

    Use this tool for open-ended, architectural, or conceptual questions about how the
    codebase works, what specific functions or modules do, or where concepts/features
    are implemented. Unlike Git history tools, this returns actual code content, AST structures,
    docstrings, implementation bodies, and hierarchical parent/child scope relationships.

    Args:
        query_text: A natural language search query describing the feature, concept,
          or code entity you are looking for.
          Examples:
            - "How is user authentication and session handling implemented?"
            - "Find where request context local objects are defined."
            - "What functions handle JSON response parsing?"
            - "Show implementation of Blueprint registration logic."

    Returns:
        List[dict]: A list of matched AST nodes ranked by relevance score, where each item contains:
            - 'id': Unique AST node identifier (e.g., 'src/flask/app.py#FILE.Flask:10:0__CODE')
            - 'name': Name of the code entity (function, class, module, or chunk)
            - 'entity_type': Uppercased entity type (e.g., 'FUNCTION', 'CLASS', 'MODULE')
            - 'file_path': File path where the code entity resides
            - 'docstring': Associated docstring or comments for the entity
            - 'implementation_body': Full source code/implementation body
            - 'parent_scope': Name of parent enclosing scope/class ('Top-Level' if none)
            - 'parent_type': Uppercased entity type of parent scope
            - 'parent_docstring': Parent scope's docstring
            - 'parent_body': Parent scope's source code
            - 'start_line', 'end_line', 'start_column', 'end_column': Code line & column boundaries
            - 'children': List of child AST entities containing name, type, signature, docstring, body
            - 'next_chunks': Adjacent code chunks for sequential context
            - 'score': Similarity/relevance score for the search match
    """
    query_vector = embeddings.embed_query(query_text)
    safe_query_text = sanitize_lucene_query(query_text)

    if not safe_query_text.strip():
        safe_query_text = query_text

    cypher_query = """
    // 1. Collect top 40 Vector hits
    CALL () {
      MATCH (node:ASTNode)
      SEARCH node IN (VECTOR INDEX code_ast_index FOR $query_vector LIMIT 40) SCORE AS v_score
      WHERE toUpper(node.entity_type) IN $supported_entity_list
        AND NOT toUpper(node.entity_type) ENDS WITH "_CHUNK"
      RETURN node ORDER BY v_score DESC
    }
    WITH collect(node) AS v_nodes

    // 2. Collect top 40 Full-Text hits
    // 2.1. Prepare Lucene query with wildcard formatting & bind parameter to a local variable
    WITH $safe_target AS target,
        $supported_entity_list AS supported_list, v_nodes,
        CASE
          WHEN $safe_target CONTAINS ' ' OR $safe_target CONTAINS '*' THEN $safe_target
          ELSE $safe_target + '*'
        END AS lucene_target

    // 2.2. Collect top 40 Full-Text hits with wildcard support (using plain variable names)
    CALL (lucene_target, supported_list) {
      CALL db.index.fulltext.queryNodes("code_fulltext_index", lucene_target) YIELD node, score AS ft_score
      WHERE toUpper(node.entity_type) IN supported_list
        AND NOT toUpper(node.entity_type) ENDS WITH "_CHUNK"
      RETURN node ORDER BY ft_score DESC LIMIT 40
    }
    WITH v_nodes, collect(node) AS ft_nodes

    // 3. Merge candidate set
    WITH apoc.coll.union(v_nodes, ft_nodes) AS candidate_nodes, v_nodes, ft_nodes
    UNWIND candidate_nodes AS node

    // 4. Calculate RRF (k = 60)
    WITH node,
        coll.indexOf(v_nodes, node) AS v_rank,
        coll.indexOf(ft_nodes, node) AS ft_rank
    WITH node,
        (CASE WHEN v_rank >= 0 THEN 1.0 / (60.0 + (v_rank + 1)) ELSE 0.0 END) +
        (CASE WHEN ft_rank >= 0 THEN 1.0 / (60.0 + (ft_rank + 1)) ELSE 0.0 END) AS score

    // 1. Preserve variables & filter test paths early
    WITH node,
        score,
        toLower(coalesce(node.file_path, split(node.id, '#')[0])) AS path
    WHERE NOT (
        // Directory containers (including root relative paths)
        path CONTAINS "/test/"
        OR path CONTAINS "/tests/"
        OR path CONTAINS "/spec/"
        OR path CONTAINS "/specs/"
        OR path CONTAINS "/__tests__/"
        OR path CONTAINS "/fixtures/"
        OR path CONTAINS "fixtures/"
        OR path CONTAINS "/mocks/"
        OR path CONTAINS "mocks/"
        OR path CONTAINS "/examples/"
        OR path CONTAINS "examples/"
        OR path STARTS WITH "test/"
        OR path STARTS WITH "/test"
        OR path STARTS WITH "/tests"
        OR path STARTS WITH "/spec"
        OR path STARTS WITH "/specs"
        OR path STARTS WITH "/__tests__"
        OR path STARTS WITH "/fixtures"
        OR path STARTS WITH "fixtures"
        OR path STARTS WITH "/mocks"
        OR path STARTS WITH "mocks"
        OR path STARTS WITH "/examples"
        OR path STARTS WITH "examples"
        OR path STARTS WITH "tests/"
        OR path STARTS WITH "spec/"
        OR path STARTS WITH "specs/"

        // Exact file name prefix/suffix boundaries
        OR path CONTAINS "/test_"
        OR path STARTS WITH "test_"
        OR path CONTAINS "_test."
        OR path CONTAINS ".test."
        OR path CONTAINS ".spec."
        OR path CONTAINS "_spec."
        OR path CONTAINS "_unittest."
    )

    // 2. Compute scores, priorities, and apply LIMIT BEFORE graph traversals
    WITH node,
        score,
        CASE toUpper(node.entity_type)
            WHEN "MODULE" THEN 1
            WHEN "NAMESPACE" THEN 1

            WHEN "CLASS" THEN 2
            WHEN "STRUCT" THEN 2
            WHEN "INTERFACE" THEN 2
            WHEN "TRAIT" THEN 2

            WHEN "METHOD" THEN 3
            WHEN "FUNCTION" THEN 3
            WHEN "CONSTRUCTOR" THEN 3
            WHEN "CLOSURE" THEN 3
            WHEN "NESTED_FUNCTION" THEN 3

            WHEN "RECORD" THEN 4
            WHEN "ENUM" THEN 4
            WHEN "UNION" THEN 4
            WHEN "TYPE_ALIAS" THEN 4

            WHEN "TABLE" THEN 5
            WHEN "VIEW" THEN 5
            WHEN "MATERIALIZED_VIEW" THEN 5
            WHEN "INDEX" THEN 5
            WHEN "SCHEMA" THEN 5
            WHEN "TYPE" THEN 5

            WHEN "HTML_ELEMENT" THEN 6
            WHEN "RULESET" THEN 6
            WHEN "AT_RULE" THEN 6

            WHEN "MARKDOWN_MODULE" THEN 7
            WHEN "MARKDOWN_HEADING" THEN 8
            WHEN "MARKDOWN_CODE_BLOCK" THEN 9
            WHEN "MARKDOWN_TABLE" THEN 10
            WHEN "JSON_STRUCTURE" THEN 11
            WHEN "SCRIPT" THEN 12

            ELSE 99
        END AS entity_priority,
        CASE WHEN node.implementation_body IS NOT NULL AND trim(node.implementation_body) <> "" THEN 1 ELSE 0 END AS has_body,
        CASE WHEN node.associated_docstring IS NOT NULL AND trim(node.associated_docstring) <> "" THEN 1 ELSE 0 END AS has_docstring

    ORDER BY
        score DESC,
        entity_priority ASC,
        has_body DESC,
        has_docstring DESC,
        node.start_line ASC
    LIMIT 40

    // 3. Traversal runs ONLY on top 40 survived nodes
    OPTIONAL MATCH (parent:ASTNode)-[:HAS_CHILD]->(node)
    OPTIONAL MATCH (node)-[:HAS_CHILD]->(child:ASTNode)
    OPTIONAL MATCH (node)-[:HAS_CHUNK]->(chunk:ASTNode)
    OPTIONAL MATCH (chunk)-[:NEXT_CODE_CHUNK|NEXT_DOCUMENT_CHUNK]->(next_chunk:ASTNode)

    WITH node, parent, score,
      [c IN collect(DISTINCT child) WHERE c IS NOT NULL] AS children_list,
      [ch IN collect(DISTINCT chunk) WHERE ch IS NOT NULL] AS chunks_list,
      [nc IN collect(DISTINCT next_chunk) WHERE nc IS NOT NULL] AS next_chunks_list

    RETURN
        node.id AS id,
        node.name AS name,
        toUpper(node.entity_type) AS entity_type,
        coalesce(node.file_path, split(node.id, '#')[0]) AS file_path,

        coalesce(node.associated_docstring, '') AS docstring,
        coalesce(node.implementation_body, '') AS implementation_body,

        coalesce(parent.name, 'Top-Level') AS parent_scope,
        toUpper(coalesce(parent.entity_type, 'NONE')) AS parent_type,
        coalesce(parent.associated_docstring, '') AS parent_docstring,
        coalesce(parent.implementation_body, '') AS parent_body,
        node.start_line AS start_line,
        node.end_line AS end_line,
        node.start_column AS start_column,
        node.end_column AS end_column,

        [c IN children_list | {
            name: c.name,
            type: toUpper(c.entity_type),
            file_path: coalesce(c.file_path, split(c.id, '#')[0]),
            signature: coalesce(c.signature, c.name),
            docstring: coalesce(c.associated_docstring, ''),
            body: coalesce(c.implementation_body, '')
        }] AS children,

        [ch IN chunks_list
          WHERE ch IS NOT NULL
          |
          {
              id: ch.id,
              name: ch.name,
              type: toUpper(ch.entity_type),
              body: coalesce(ch.implementation_body, ''),
              chunk_index: ch.chunk_index,
              total_chunks: ch.total_chunks
          }
        ] AS chunks,

        [nc IN next_chunks_list | {
            id: nc.id,
            body: coalesce(nc.implementation_body, '')
        }] AS next_chunks,
        score
    ORDER BY score DESC
    """
    initialize_search_indexes(graph)
    raw_results = graph.query(
        cypher_query,
        {"query_vector": query_vector, "safe_target": safe_query_text, "supported_entity_list":SUPPORTED_ENTITY_TYPES}
    )

    # Filter out test files
    filtered = [r for r in raw_results if not is_test_file(r.get("file_path", ""))]
    return filtered if filtered else []

def escape_fulltext_query(query: str) -> str:
    """Escapes Lucene special characters for Neo4j fulltext search."""
    if not query:
        return ""
    # List of Lucene special characters: + - && || ! ( ) { } [ ] ^ " ~ * ? : \ /
    # Escape special characters with a backslash
    escaped = re.sub(r'([+\-&|!(){}\[\]^"~*?:\\/])', r'\\\1', query)
    return escaped.strip()

import re

def is_ast_graph_query(query_str: str) -> bool:
    target = query_str.strip().lower()

    # Reject only explicit system-level architecture queries

    graph_unsupported_keywords = {
        "repository",
        "repo",
        "architecture",
        "architecture diagram",
        "dependency graph",
        "overall dependency graph",
        "call graph",
        "system architecture",
        "folder structure",
        "directory tree",
        "module structure",
        "project structure",
        "file tree",
        "project tree",
        "class hierarchy diagram",
        "module dependency matrix",
        "dependency matrix",
        "code map",
        "class diagram"
    }

    # Exact system-level request
    if target in graph_unsupported_keywords:
        return False

    # Reject global architecture requests

    query_words = set(
        re.findall(r'\b[a-z0-9_]+\b', target)
    )

    global_terms = {
        "repository",
        "repo",
        "architecture",
        "diagram"
    }

    if not global_terms.isdisjoint(query_words):

        # Allow if clearly referring to a code symbol,
        # e.g. draw_architecture_diagram()
        if "_" in target or re.match(
            r'^[a-z0-9]+[A-Z]',
            query_str.strip()
        ):
            return True

        return False
    
    # File paths and filenames are allowed

    return True


def is_ast_git_query(file_path_or_name: str) -> bool:
    target = file_path_or_name.strip().lower()

    # Reject paths containing slashes (e.g., src/flask, /app)
    if "/" in target or "\\" in target:
        return False

    repo_keywords = {
        # System / Repository / Hierarchy
        "repository", "repo", "project", "directory", "folder", "package",
        "project tree", "class hierarchy", "dependency matrix",

        # Author / Contributor level queries
        "author", "authors", "contributor", "contributors", "who modified",
        "who wrote", "who fixed", "who refactored", "committer",

        # Global Git Operations & History
        "git", "git push", "git rebase", "git checkout", "git status",
        "git cherry-pick", "commit", "commits", "latest commits",
        "repository history", "all commit history", "changelog", "release notes", "pdf"
    }

    # Match standalone words or exact phrases
    query_words = set(re.findall(r'\b[a-z0-9_]+\b', target))

    # If the user literally queries "repository", "latest commits", etc.
    if target in repo_keywords or not repo_keywords.isdisjoint(query_words):
        # Allow multi-word AST symbol references if they look like code methods
        # (e.g., "get_commit_hash" or "process_file")
        if "_" in target or re.match(r'^[a-z0-9]+[A-Z]', file_path_or_name.strip()):
            return True
        return False

    return True


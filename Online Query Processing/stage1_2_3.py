def dynamic_prune_candidates(
    sorted_candidates: List[Dict[str, Any]],
    min_keep: int = 2,
    max_keep: int = 8,
    relative_drop_ratio: float = 0.40,
    absolute_floor: float = 0.15
) -> List[Dict[str, Any]]:
    if not sorted_candidates:
        return []

    top_score = sorted_candidates[0]["rerank_score"]

    # Dynamic cutoff: drop items that fall 40% below the top candidate's score
    dynamic_threshold = max(top_score * (1.0 - relative_drop_ratio), absolute_floor)

    kept = []
    for cand in sorted_candidates:
        score = cand["rerank_score"]

        # Always keep up to min_keep candidates if available
        if len(kept) < min_keep:
            kept.append(cand)
        # For additional candidates, enforce the dynamic score threshold
        elif score >= dynamic_threshold and len(kept) < max_keep:
            kept.append(cand)

    return kept

def min_max_normalize(values: List[float]) -> List[float]:
    if not values:
        return []

    min_val = min(values)
    max_val = max(values)

    # If all scores are identical, treat them as neutral/equal.
    if max_val == min_val:
        return [1.0] * len(values)

    return [
        (value - min_val) / (max_val - min_val)
        for value in values
    ]


def build_graph_relationship_text(
    candidate: Dict[str, Any],
    all_candidates: List[Dict[str, Any]]
) -> str:
    """
    Convert explicit graph relationships into natural-language
    structural evidence.

    This does NOT inspect the user's wording.
    """

    name = candidate.get("name", "Unknown")
    entity_type = candidate.get("entity_type", "UNKNOWN")
    parent_scope = candidate.get("parent_scope", "Top-Level")

    descriptions = []

    # Parent relationship
    if (
        parent_scope
        and parent_scope != "Top-Level"
        and candidate.get("parent_type") not in (None, "NONE")
    ):
        descriptions.append(
            f"{name} is contained inside "
            f"{parent_scope}, which is a "
            f"{candidate.get('parent_type', 'UNKNOWN')}."
        )

    # Child relationships
    children = candidate.get("children") or []

    for child in children:

        child_name = child.get("name")

        if not child_name:
            continue

        child_type = child.get(
            "type",
            "UNKNOWN"
        )

        descriptions.append(
            f"{name} contains "
            f"{child_name}, which is a "
            f"{child_type}."
        )

    # Sibling relationships
    # Siblings are derived from shared parent_id.
    # They are NOT next_chunks.
    candidate_parent_id = candidate.get("parent_id")

    if candidate_parent_id:

        candidate_id = str(
            candidate.get("id")
            or candidate.get("node_id")
            or ""
        )

        for other in all_candidates:

            other_id = str(
                other.get("id")
                or other.get("node_id")
                or ""
            )

            if other_id == candidate_id:
                continue

            if (
                other.get("parent_id")
                and str(other.get("parent_id"))
                == str(candidate_parent_id)
            ):
                other_name = other.get("name")

                if other_name:
                    descriptions.append(
                        f"{name} and {other_name} are "
                        f"structural siblings defined under "
                        f"the same parent {parent_scope}."
                    )

    # Continuation chunks
    next_chunks = candidate.get("next_chunks") or []

    if next_chunks:
        descriptions.append(
            f"{name} has "
            f"{len(next_chunks)} continuation sibling chunk(s) "
            f"belonging to the same logical AST entity."
        )

    # If no relationship exists
    if not descriptions:
        descriptions.append(
            f"{name} has no explicit graph relationship "
            f"to the other retrieved candidates."
        )

    return "\n".join(descriptions)


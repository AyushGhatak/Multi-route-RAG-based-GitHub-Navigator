def resolve_repo_path(extracted_path: Optional[str] = None) -> str:
    """Resolve and validate repo directory."""
    candidates = []

    if extracted_path and extracted_path.strip():
        candidates.append(os.path.expanduser(extracted_path.strip()))

    candidates.append(DEFAULT_REPO_PATH)
    candidates.append(os.getcwd())

    for path in candidates:
        abs_path = os.path.abspath(path)
        if os.path.isdir(abs_path) and os.path.exists(
            os.path.join(abs_path, ".git")
        ):
            return abs_path

    # Safe depth-limited search without entering .git folders
    try:
        for root, dirs, _ in os.walk("."):
            if ".git" in dirs:
                dirs.remove(".git")  # Prevent searching inside .git
                return os.path.abspath(root)
    except Exception:
        pass

    return os.path.abspath(".")


def run_git_cmd(
    cmd: List[str], repo_path: Optional[str] = None
) -> Tuple[str, Optional[str]]:
    """Execute a Git command safely without output pollution.

    Returns Tuple[stdout, error_message].
    """
    target_path = resolve_repo_path(repo_path)

    git_dir = os.path.join(target_path, ".git")
    if not os.path.exists(git_dir):
        err = f"'{target_path}' is not a valid Git repository (missing .git directory)."
        return "", err

    full_cmd = ["git", "-C", target_path] + cmd

    try:
        result = subprocess.run(
            full_cmd,
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            text=True,
            check=False,
            encoding="utf-8",
            errors="replace",
        )
        if result.returncode != 0:
            err_msg = (
                result.stderr.strip()
                or f"Command failed with exit code {result.returncode}"
            )
            return "", err_msg
        return result.stdout.strip(), None
    except FileNotFoundError:
        return "", "Git executable not found in system PATH."
    except Exception as e:
        return "", f"Subprocess execution error: {str(e)}"



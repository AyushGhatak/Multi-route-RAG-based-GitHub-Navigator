import os
import re
from datetime import datetime, timezone
from typing import List, Dict, Any
from qwen_tokenizer import get_tokenizer

tokenizer = get_tokenizer("Qwen/Qwen2.5-Coder-7B-Instruct")

# Token limits for different Git payload types
GIT_TOKEN_LIMITS = {
    "BLAME_CODE": 400,
    "BLAME_BLOCK": 500,
    "COMMIT_LOG": 300,
    "COMMIT_DIFF": 700
}

def count_tokens(text: str) -> int:
    if not text:
        return 0
    return len(tokenizer.encode(text))


def format_timestamp(ts: Any) -> str:
    """Converts Unix string/int timestamp to readable ISO format."""
    if not ts:
        return "Unknown Date"
    try:
        dt = datetime.fromtimestamp(int(ts), tz=timezone.utc)
        return dt.strftime("%Y-%m-%d %H:%M UTC")
    except (ValueError, TypeError):
        return str(ts)


def compress_blame_records(blame_candidates: List[Dict[str, Any]]) -> List[Dict[str, Any]]:
    """
    Consolidates contiguous line-by-line blame records sharing the same commit and author
    into unified line blocks using Run-Length Encoding (RLE).
    """
    if not blame_candidates:
        return []

    # Sort blame records by file and line number
    sorted_blame = sorted(
        blame_candidates,
        key=lambda x: (x.get("file_path", ""), x.get("line_number", 0))
    )

    consolidated = []
    current_block = None

    for record in sorted_blame:
        file_path = record.get("file_path", "")
        line_num = record.get("line_number", 0)
        commit_hash = record.get("commit_hash", "") or record.get("commit", "unknown")

        # Schema field fallback fixes
        author = record.get("author_name") or record.get("author") or "Unknown"
        email = record.get("author_email", "")
        author_str = f"{author} <{email}>" if email else author

        date_raw = record.get("timestamp") or record.get("date") or ""
        date = format_timestamp(date_raw)

        # Schema fix: raw payload uses `source_line`
        code = record.get("source_line", record.get("code", record.get("line_content", ""))).rstrip()

        if current_block is None:
            current_block = {
                "file_path": file_path,
                "start_line": line_num,
                "end_line": line_num,
                "commit_hash": commit_hash,
                "author": author_str,
                "date": date,
                "code_lines": [(line_num, code)]
            }
        else:
            # Check contiguity and commit identity
            is_adjacent = (file_path == current_block["file_path"]) and (line_num == current_block["end_line"] + 1)
            is_same_commit = (commit_hash == current_block["commit_hash"])

            if is_adjacent and is_same_commit:
                current_block["end_line"] = line_num
                current_block["code_lines"].append((line_num, code))
            else:
                consolidated.append(current_block)
                current_block = {
                    "file_path": file_path,
                    "start_line": line_num,
                    "end_line": line_num,
                    "commit_hash": commit_hash,
                    "author": author_str,
                    "date": date,
                    "code_lines": [(line_num, code)]
                }

    if current_block:
        consolidated.append(current_block)

    return consolidated

def truncate_text(text: str, token_limit: int) -> str:
    if not text:
        return ""

    tokens = tokenizer.encode(text)

    if len(tokens) <= token_limit:
        return text

    marker = "\n... [truncated]"
    marker_tokens = tokenizer.encode(marker)

    if token_limit <= len(marker_tokens):
        return tokenizer.decode(tokens[:token_limit])

    content_limit = token_limit - len(marker_tokens)

    return tokenizer.decode(tokens[:content_limit]) + marker

def truncate_code_lines_by_tokens(
    code_lines: List[tuple],
    token_limit: int
) -> str:
    if not code_lines:
        return ""

    marker = "... [remaining lines truncated]"
    marker_tokens = count_tokens(marker)

    selected = []
    used_tokens = 0

    for line_number, code in code_lines:
        line_text = f"  {line_number}: {code}\n"
        line_tokens = count_tokens(line_text)

        if used_tokens + line_tokens + marker_tokens > token_limit:
            break

        selected.append(line_text)
        used_tokens += line_tokens

    if len(selected) < len(code_lines):
        selected.append(marker + "\n")

    return "".join(selected)


def step2_process_git_context(
    query: str,
    raw_git_result: Dict[str, Any],
    max_token_budget: int = 2800
) -> Dict[str, Any]:
    """
    Compresses and formats Git blame, diff, and history results
    into the unified Stage-3 context representation.
    """
    intent = raw_git_result.get("intent", "unknown")
    metadata = raw_git_result.get("query_metadata", {})
    stage1_message = raw_git_result.get("message")

    blame_candidates = raw_git_result.get("blame_candidates", [])
    history_candidates = raw_git_result.get("history_candidates", [])
    commit_diffs = raw_git_result.get("commit_diffs", [])
    errors = raw_git_result.get("errors", [])

    compressed_blocks = []
    accumulated_tokens = 0


    # STEP 1: Process Blame Records
    consolidated_blame = compress_blame_records(blame_candidates)

    for block in consolidated_blame:

        header = (
            f"--- [GIT BLAME] File: {block['file_path']} "
            f"(Lines {block['start_line']}-{block['end_line']}) ---\n"
            f"Commit: {block['commit_hash'][:10]} | "
            f"Author: {block['author']} | "
            f"Date: {block['date']}\n"
            f"Code Block:\n"
        )

        footer = "\n\n"

        available_code_tokens = (
            GIT_TOKEN_LIMITS["BLAME_BLOCK"]
            - count_tokens(header)
            - count_tokens(footer)
        )

        if available_code_tokens <= 0:
            continue

        code_str_truncated = truncate_code_lines_by_tokens(
            block["code_lines"],
            available_code_tokens
        )

        block_text = header + code_str_truncated + footer

        block_tokens = count_tokens(block_text)

        if accumulated_tokens + block_tokens > max_token_budget:
            break

        accumulated_tokens += block_tokens

        is_truncated = (
            "... [remaining lines truncated]"
            in code_str_truncated
        )

        compressed_blocks.append({
            "type": "blame_block",
            "content": block_text,
            "token_count": block_tokens,
            "is_truncated": is_truncated,
            "metadata": block
        })

    # STEP 2: Process Commit Diffs
    for diff_item in commit_diffs:

        diff_text = (
            diff_item
            if isinstance(diff_item, str)
            else diff_item.get(
                "diff_content",
                diff_item.get("patch", "")
            )
        )

        header = "--- [GIT COMMIT DIFF] ---\n"
        footer = "\n\n"

        available_diff_tokens = (
            GIT_TOKEN_LIMITS["COMMIT_DIFF"]
            - count_tokens(header)
            - count_tokens(footer)
        )

        if available_diff_tokens <= 0:
            continue

        diff_truncated = truncate_text(
            diff_text,
            available_diff_tokens
        )

        formatted_diff = header + diff_truncated + footer

        diff_tokens = count_tokens(formatted_diff)

        if accumulated_tokens + diff_tokens > max_token_budget:
            break

        accumulated_tokens += diff_tokens

        is_truncated = (
            len(tokenizer.encode(diff_text))
            > available_diff_tokens
        )

        compressed_blocks.append({
            "type": "commit_diff",
            "content": formatted_diff,
            "token_count": diff_tokens,
            "is_truncated": is_truncated,
            "metadata": diff_item
        })

    # STEP 3: Process Commit History Logs
    for history in history_candidates:

        commit_hash = (
            history.get("commit_hash")
            or history.get("commit", "")
        )

        author = (
            history.get("author_name")
            or history.get("author", "Unknown")
        )

        date_raw = (
            history.get("timestamp")
            or history.get("date", "")
        )

        date = format_timestamp(date_raw)

        message = (
            history.get("commit_message")
            or history.get("message")
            or history.get("summary")
            or ""
        ).strip()


        header = (
            f"--- [GIT COMMIT LOG] Commit: {commit_hash[:10]} ---\n"
            f"Author: {author} | Date: {date}\n"
            f"Message: "
        )

        footer = "\n\n"

        available_message_tokens = (
            GIT_TOKEN_LIMITS["COMMIT_LOG"]
            - count_tokens(header)
            - count_tokens(footer)
        )

        if available_message_tokens <= 0:
            continue

        message_truncated = truncate_text(
            message,
            available_message_tokens
        )

        history_text = header + message_truncated + footer

        history_tokens = count_tokens(history_text)

        if accumulated_tokens + history_tokens > max_token_budget:
            break

        accumulated_tokens += history_tokens

        is_truncated = (
            len(tokenizer.encode(message))
            > available_message_tokens
        )

        compressed_blocks.append({
            "type": "history_log",
            "content": history_text,
            "token_count": history_tokens,
            "is_truncated": is_truncated,
            "metadata": history
        })

    formatted_prompt_payload = "".join([b["content"] for b in compressed_blocks])

    # Determine message field value
    total_records = len(blame_candidates) + len(history_candidates) + len(commit_diffs)

    output_message = None if compressed_blocks else stage1_message

    return {
        "formatted_git_payload": formatted_prompt_payload,
        "compressed_blocks": compressed_blocks,
        # Unified Stage-3 input field for Git route
        "compressed_context": compressed_blocks,
        "intent_detected": intent,
        "message": output_message,
        "query_metadata": metadata,
        "raw_record_counts": {
            "blame": len(blame_candidates),
            "history": len(history_candidates),
            "diffs": len(commit_diffs)
        },
        "final_block_count": len(compressed_blocks),
        "total_tokens_used": accumulated_tokens,
        "errors": errors,
        "context_type": "git"
    }


def is_test_file(file_path: str) -> bool:
    """Repository-agnostic test file detector tailored for Python, Go, C, C++, Java, Rust,

    TypeScript, JavaScript, Ruby, CSS, HTML, JSON, Markdown, SQL, and CSV.
    """
    if not file_path:
        return False

    path_lower = file_path.lower().replace("\\", "/")
    parts = path_lower.split("/")
    filename = parts[-1]

    # Base name without extension for flexible matching (e.g. "test_user.cpp" -> "test_user")
    base_name, ext = os.path.splitext(filename)

    # 1. Directory-level test containers (Expanded for C/C++, Java, JS/TS, SQL)
    test_dirs = {
        "test", "tests", "spec", "specs", "__tests__", "__test__",
        "testing", "fixtures", "fixture", "testdata", "mocks", "mock"
    }
    if any(part in test_dirs for part in parts[:-1]):
        return True

    # 2. Universal File Naming Patterns by Language:
    # ---------------------------------------------------------------------
    # Python: test_*.py, *_test.py
    # Go: *_test.go
    # JS/TS: *.test.js, *.spec.ts, *.test.jsx, *.spec.tsx, etc.
    # Java: *Test.java, *Tests.java, Test*.java, *TestCase.java
    # Rust: tests.rs, *_test.rs, test_*.rs
    # Ruby: *_spec.rb, test_*.rb, *_test.rb
    # C / C++: test_*.c, *_test.cpp, *_unittest.cc, t_*.c, check_*.c
    # Web/Data (CSS/HTML/JSON/MD/SQL/CSV): test_*.json, *_fixture.sql, mock_*.csv
    # ---------------------------------------------------------------------

    # Check common prefix/suffix patterns on the file stem
    if (
        base_name.startswith("test_")
        or base_name.startswith("test-")
        or base_name.startswith("mock_")
        or base_name.startswith("fixture_")
        or base_name.endswith("_test")
        or base_name.endswith("-test")
        or base_name.endswith("_spec")
        or base_name.endswith("-spec")
        or base_name.endswith("_mock")
        or base_name.endswith("_fixture")
    ):
        return True

    # Language/Framework-specific exact pattern matching
    if (
        # JS / TS dot notation: e.g., app.test.ts, component.spec.jsx
        ".test." in filename
        or ".spec." in filename
        # Java conventions
        or base_name.endswith("testcase")
        or (base_name.startswith("test") and ext == ".java")
        # C / C++ GoogleTest & Catch2 conventions
        or base_name.endswith("_unittest")
        or base_name.endswith("_check")
        or base_name.startswith("check_")
        or base_name.startswith("t_")
        # Standalone Rust test runner file
        or filename == "tests.rs"
    ):
        return True

    return False


def sanitize_lucene_query(text: str) -> str:
    """Escape special Lucene characters for full-text search safety."""
    special_chars = r'[\+\-\!\(\)\{\}\[\]\^"\~\*\?\:\\]'
    return re.sub(special_chars, r'\\g<0>', text)



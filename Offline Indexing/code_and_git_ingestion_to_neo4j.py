def ingest_complete_codebase_and_git(
    graph, ast_nodes: list, commit_logs: list, blame_records: list, batch_size: int = 1000
):
    """Executes safe batch UNWIND queries to populate structural and Git data in Neo4j."""

    # Ingest AST Structure Nodes
    ast_query = """
    UNWIND $nodes AS node

    // 1. Merge and populate AST / Sub-Chunk Node
    MERGE (n:ASTNode {id: node.id})
    SET n.name = node.name,
        n.entity_type = node.entity_type,
        n.signature = node.signature,
        n.implementation_body = node.implementation_body,
        n.associated_docstring = node.associated_docstring,
        n.parent_id = node.parent_id,
        n.parent_type = node.parent_type,

        // Scope Range Properties
        n.start_line = toInteger(node.scope_range.start_line),
        n.end_line = toInteger(node.scope_range.end_line),
        n.start_column = toInteger(node.scope_range.start_column),
        n.end_column = toInteger(node.scope_range.end_column),

        // Chunk Metadata Properties
        n.chunk_index = toInteger(node.chunk_metadata.chunk_index),
        n.total_chunks = toInteger(node.chunk_metadata.total_chunks),
        n.is_subchunked = toBoolean(node.chunk_metadata.is_subchunked),

        // Clean file path parsing across all document & code suffixes
        n.file_path = split(node.id, '#')[0]
    """

    if ast_nodes:
        print(f"Ingesting {len(ast_nodes)} AST nodes in batches of {batch_size}...")
        for i in range(0, len(ast_nodes), batch_size):
            chunk = ast_nodes[i : i + batch_size]
            graph.query(ast_query, {"nodes": chunk})

        print("Ingested AST nodes successfully!")
        # Create AST Structural Relationships
        ast_relationship_query = """
        MATCH (n:ASTNode)
        WHERE n.parent_id IS NOT NULL
          AND n.parent_id <> ""

        OPTIONAL MATCH (p:ASTNode)
        WHERE p.id = n.parent_id
          OR p.id = n.parent_id + "__CODE"
          OR p.id = n.parent_id + "#DOCUMENT"

        WITH n, p
        WHERE p IS NOT NULL

        FOREACH (_ IN CASE
            WHEN n.is_subchunked = true
            AND n.entity_type ENDS WITH "_CHUNK"
            THEN [1]
            ELSE []
        END |
            MERGE (p)-[r:HAS_CHUNK]->(n)
            SET r.parent_type = n.parent_type,
                r.chunk_index = n.chunk_index,
                r.total_chunks = n.total_chunks
        )

        FOREACH (_ IN CASE
            WHEN NOT (
                n.is_subchunked = true
                AND n.entity_type ENDS WITH "_CHUNK"
            )
            THEN [1]
            ELSE []
        END |
            MERGE (p)-[r:HAS_CHILD]->(n)
            SET r.parent_type = n.parent_type
        )
        """

        print("Creating AST parent/chunk structural relationships...")
        graph.query(ast_relationship_query)

        # Ingest Git Log History Nodes
        git_log_query = """
        UNWIND $commits AS c
        WITH c WHERE c.author IS NOT NULL AND c.commit_hash IS NOT NULL

        MERGE (a:Author {email: c.author.email})
        ON CREATE SET a.name = c.author.name

        MERGE (cm:Commit {hash: c.commit_hash})
        SET cm.message = c.message,
            cm.date = c.committed_date,
            cm.lines_changed = c.stats.lines_changed

        MERGE (a)-[:COMMITTED]->(cm)
        """

        if commit_logs:
            print(f"Ingesting {len(commit_logs)} commits in batches of {batch_size}...")
            for i in range(0, len(commit_logs), batch_size):
                chunk = commit_logs[i : i + batch_size]
                graph.query(git_log_query, {"commits": chunk})

    # Intersect Line Ranges via Blame Records
    blame_query = """
    UNWIND $blame AS b

    // Target line number
    WITH b, toInteger(b.line_number) AS blame_line
    WHERE blame_line IS NOT NULL

    MATCH (n:ASTNode)
    WHERE n.file_path = b.file_path
      AND n.start_line IS NOT NULL
      AND n.end_line IS NOT NULL
      AND toInteger(n.start_line) <= blame_line
      AND toInteger(n.end_line) >= blame_line

    // Pick the innermost/most specific AST node (smallest line span)
    WITH b, n, (toInteger(n.end_line) - toInteger(n.start_line)) AS line_span
    ORDER BY line_span ASC
    WITH b, collect(n)[0] AS target_node
    WHERE target_node IS NOT NULL

    // Link Author and Commit
    MERGE (a:Author {email: b.author_email})
    MERGE (cm:Commit {hash: b.associated_commit_hash})

    MERGE (a)-[:DEVELOPED]->(target_node)
    MERGE (cm)-[:MODIFIED_STRUCTURE]->(target_node)
    """

    if blame_records:
        print(f"Ingesting {len(blame_records)} blame records in batches of {batch_size}...")
        for i in range(0, len(blame_records), batch_size):
            chunk = blame_records[i : i + batch_size]
            graph.query(blame_query, {"blame": chunk})

    # Chain Sequential Text Chunks via NEXT_DOCUMENT_CHUNK
    next_doc_chunk_query = """
    MATCH (c:ASTNode)
    WHERE c.entity_type = 'TEXT_DOCUMENT_CHUNK'

    WITH coalesce(c.parent_id, split(c.id, '#')[0]) AS parent_group, c,
         CASE
           WHEN c.chunk_index IS NOT NULL THEN toInteger(c.chunk_index)
           WHEN c.id CONTAINS '#DOCUMENT_PART_' THEN toInteger(split(c.id, '#DOCUMENT_PART_')[1])
           ELSE toInteger(c.start_line)
         END AS calculated_index

    WITH parent_group, c ORDER BY calculated_index ASC, c.id ASC
    WITH parent_group, collect(c) AS chunks
    WHERE size(chunks) > 1

    UNWIND range(0, size(chunks) - 2) AS i
    WITH chunks[i] AS current_chunk, chunks[i + 1] AS next_chunk
    MERGE (current_chunk)-[:NEXT_DOCUMENT_CHUNK]->(next_chunk)
    """

    print("Linking sequential text chunks via NEXT_DOCUMENT_CHUNK...")
    graph.query(next_doc_chunk_query)

    # Chain Sequential Code Chunks via NEXT_CODE_CHUNK
    next_code_chunk_query = """
    MATCH (c:ASTNode)
    WHERE c.entity_type ENDS WITH '_CHUNK'
      AND c.entity_type <> 'TEXT_DOCUMENT_CHUNK'

    WITH coalesce(c.parent_id, split(c.id, '#')[0]) AS parent_group, c,
         CASE
           WHEN c.chunk_index IS NOT NULL THEN toInteger(c.chunk_index)
           WHEN c.id CONTAINS '__CODE_PART_' THEN toInteger(split(c.id, '__CODE_PART_')[1])
           ELSE toInteger(c.start_line)
         END AS calculated_index

    WITH parent_group, c ORDER BY calculated_index ASC, c.id ASC
    WITH parent_group, collect(c) AS chunks
    WHERE size(chunks) > 1

    UNWIND range(0, size(chunks) - 2) AS i
    WITH chunks[i] AS current_chunk, chunks[i + 1] AS next_chunk
    MERGE (current_chunk)-[:NEXT_CODE_CHUNK]->(next_chunk)
    """

    print("Linking sequential code chunks via NEXT_CODE_CHUNK...")
    graph.query(next_code_chunk_query)


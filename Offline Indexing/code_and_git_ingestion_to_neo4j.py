# Git Codebase Analyzer
class GitCodebaseAnalyzer:
    def __init__(self, repo: Repo):
        self.repo = repo
        self.working_dir = repo.working_dir

    def get_commit_logs(self, limit: int = 500) -> List[Dict[str, Any]]:
        """Extracts commit logs in a clean list-of-dicts format."""
        commit_list = []
        for commit in self.repo.iter_commits(max_count=limit):
            commit_list.append({
                "id": f"{commit.hexsha}#COMMIT",
                "entity_type": "COMMIT",
                "commit_hash": commit.hexsha,
                "author": {
                    "name": commit.author.name,
                    "email": commit.author.email
                },
                "committer": {
                    "name": commit.committer.name,
                    "email": commit.committer.email
                },
                "authored_date": datetime.datetime.fromtimestamp(commit.authored_date).isoformat(),
                "committed_date": datetime.datetime.fromtimestamp(commit.committed_date).isoformat(),
                "message": commit.message.strip(),
                "parent_hashes": [parent.hexsha for parent in commit.parents],
                "stats": {
                    "insertions": commit.stats.total.get("insertions", 0),
                    "deletions": commit.stats.total.get("deletions", 0),
                    "lines_changed": commit.stats.total.get("lines", 0),
                    "files_changed": len(commit.stats.files)
                }
            })
        return commit_list

    def get_file_blame(self, absolute_filepath: str) -> List[Dict[str, Any]]:
        """Runs a Git blame on a file and maps the author metadata of every line."""
        if not os.path.exists(absolute_filepath):
            print(f"File not found for blame: {absolute_filepath}")
            return []
        try:
            blame_raw = self.repo.git.blame("-p", absolute_filepath)
        except Exception as e:
            print(f"Error running git blame on {absolute_filepath}: {e}")
            return []
        return self._parse_porcelain_blame(blame_raw, absolute_filepath)

    def _parse_porcelain_blame(self, blame_text: str, filepath: str) -> List[Dict[str, Any]]:
        lines = blame_text.splitlines()
        commit_metadata = {}
        blame_records = []
        i, total_lines = 0, len(lines)

        while i < total_lines:
            line = lines[i]
            if not line:
                i += 1
                continue

            parts = line.split()
            sha = parts[0]
            result_line_num = int(parts[2])

            if sha not in commit_metadata:
                commit_metadata[sha] = {}
                while i < total_lines and not lines[i].startswith('\t'):
                    meta_line = lines[i]
                    if meta_line.startswith("author "):
                        commit_metadata[sha]["author_name"] = meta_line[7:]
                    elif meta_line.startswith("author-mail "):
                        commit_metadata[sha]["author_email"] = meta_line[12:].strip('<>')
                    elif meta_line.startswith("author-time "):
                        timestamp = int(meta_line[12:])
                        commit_metadata[sha]["authored_date"] = datetime.datetime.fromtimestamp(timestamp).isoformat()
                    i += 1
            else:
                while i < total_lines and not lines[i].startswith('\t'):
                    i += 1

            line_content = lines[i][1:] if i < total_lines and lines[i].startswith('\t') else ""
            blame_records.append({
                "id": f"{filepath}#LINE_{result_line_num}",
                "entity_type": "FILE_LINE_BLAME",
                "file_path": filepath,
                "line_number": result_line_num,
                "associated_commit_hash": sha,
                "author_name": commit_metadata[sha].get("author_name", "Unknown"),
                "author_email": commit_metadata[sha].get("author_email", "Unknown"),
                "authored_date": commit_metadata[sha].get("authored_date", "Unknown"),
                "line_content": line_content
            })
            i += 1
        return blame_records


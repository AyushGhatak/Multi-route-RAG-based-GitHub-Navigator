# PHASE 1 & PHASE 2 DATA COLLECTION PIPELINE

def phase_1_ingest_ast(gdrive_folder_path):
    print("Starting Phase 1: Ingesting AST Structural Files...")
    all_ast_nodes = []

    if not os.path.exists(gdrive_folder_path):
        print(f"Error: Path '{gdrive_folder_path}' does not exist.")
        return all_ast_nodes

    for filename in os.listdir(gdrive_folder_path):
        if filename.endswith(".json"):
            file_json_path = os.path.join(gdrive_folder_path, filename)
            with open(file_json_path, "r", encoding="utf-8") as f:
                try:
                    data = json.load(f)
                    nodes_list = data if isinstance(data, list) else data.get("nodes", [])
                    all_ast_nodes.extend(nodes_list)
                except Exception as e:
                    print(f"Error reading JSON file {filename}: {e}")

    print(f"Loaded {len(all_ast_nodes)} AST elements from Drive.")
    return all_ast_nodes


# Extensions to skip during Git blame harvesting
BINARY_EXTENSIONS = {
    ".png", ".jpg", ".jpeg", ".gif", ".ico", ".svg",
    ".pdf", ".zip", ".tar", ".gz", ".7z",
    ".pyc", ".pyo", ".so", ".dll", ".exe", ".bin",
    ".woff", ".woff2", ".ttf", ".eot"
}

def phase_2_harvest_git_blame(all_ast_nodes, local_repo_path, analyzer):
    print("\nStarting Phase 2: Harvesting Git Blame History...")
    all_blame_records = []
    unique_files = set()

    for node in all_ast_nodes:
        node_id = node.get("id", "")
        if "#" in node_id:
            file_path = node_id.split("#")[0]
            if file_path:
                unique_files.add(file_path)

    print(f"Discovered {len(unique_files)} unique target files to analyze.")

    for relative_path in unique_files:
        clean_rel = relative_path.lstrip("/")

        # Skip .git internal files and binary assets
        if clean_rel.startswith(".git/") or any(clean_rel.lower().endswith(ext) for ext in BINARY_EXTENSIONS):
            continue

        absolute_target_file = os.path.normpath(os.path.join(local_repo_path, clean_rel))

        try:
            file_blames = analyzer.get_file_blame(absolute_target_file)
            if file_blames:
                for record in file_blames:
                    record["file_path"] = relative_path
                all_blame_records.extend(file_blames)
        except Exception as e:
            print(f"  [Warning] Could not harvest blame for '{clean_rel}': {e}")

    print(f"Harvested {len(all_blame_records)} blame interaction records.")
    return all_blame_records

